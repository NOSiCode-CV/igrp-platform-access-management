-- Base schema for a FRESH, EMPTY database. Applied only by
-- FreshDatabaseSchemaCallback, before Flyway's first migration, and only when
-- the schema has no t_user table. Existing databases never run it.
--
-- Why it exists: the versioned migrations (V6 onwards) patch tables that
-- Hibernate and DatabaseMigrationRunner created on databases that predate
-- Flyway. On an empty database Flyway runs first, finds none of those tables,
-- and V9 fails with: relation "t_user_session" does not exist.
--
-- What it is: a schema-only pg_dump of exactly that pre-Flyway state (entity
-- tables from Hibernate plus DatabaseMigrationRunner's invariants), which is
-- the state the V6+ scripts are known to apply on. The compat suite boots
-- from an empty database through this path on every build.
--
-- Do not edit by hand to track entity changes: new schema changes belong in
-- Flyway migrations, which run on top of this file like on any database.
-- Captured 2026-10-29 from Postgres 16.

--
--

